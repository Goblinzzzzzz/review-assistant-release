async function downloadWhisperModel(modelKey, onProgress = () => {
}) {
  const preset = WHISPER_MODEL_PRESETS.find((item) => item.key === modelKey);
  if (!preset)
    throw new Error(`\u672A\u77E5 Whisper \u6A21\u578B\uFF1A${modelKey}`);
  const { promises: fs } = require("fs");
  const path = require("path");
  const https = require("https");
  const home2 = process.env.HOME || "";
  const modelDir = path.join(home2, ".whisper-models");
  const targetPath = path.join(modelDir, preset.fileName);
  const tempPath = `${targetPath}.download`;
  await fs.mkdir(modelDir, { recursive: true });
  try {
    await fs.access(targetPath);
    return targetPath;
  } catch (e) {
  }
  const url = `https://huggingface.co/ggerganov/whisper.cpp/resolve/main/${preset.fileName}`;
  await new Promise((resolve, reject) => {
    const request = (downloadUrl, redirectCount = 0) => {
      if (redirectCount > 5) {
        reject(new Error("\u6A21\u578B\u4E0B\u8F7D\u91CD\u5B9A\u5411\u8FC7\u591A"));
        return;
      }
      const req = https.get(downloadUrl, (res) => {
        if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          res.resume();
          request(new URL(res.headers.location, downloadUrl).toString(), redirectCount + 1);
          return;
        }
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`\u6A21\u578B\u4E0B\u8F7D\u5931\u8D25\uFF1AHTTP ${res.statusCode}`));
          return;
        }
        const totalBytes = Number(res.headers["content-length"] || 0);
        let downloadedBytes = 0;
        let lastReportAt = 0;
        const file = require("fs").createWriteStream(tempPath);
        res.on("data", (chunk) => {
          downloadedBytes += chunk.length;
          const now = Date.now();
          if (now - lastReportAt < 350 && downloadedBytes < totalBytes)
            return;
          lastReportAt = now;
          const percent = totalBytes ? downloadedBytes / totalBytes : 0;
          const downloadedMb = (downloadedBytes / 1024 / 1024).toFixed(1);
          const totalMb = totalBytes ? (totalBytes / 1024 / 1024).toFixed(1) : "";
          onProgress({
            progress: totalBytes ? 0.65 + percent * 0.3 : 0.72,
            detail: totalBytes ? `\u5DF2\u4E0B\u8F7D ${downloadedMb}MB / ${totalMb}MB` : `\u5DF2\u4E0B\u8F7D ${downloadedMb}MB`,
            indeterminate: !totalBytes
          });
        });
        res.pipe(file);
        file.on("finish", () => {
          file.close(resolve);
        });
        file.on("error", reject);
      });
      req.on("error", reject);
    };
    request(url);
  });
  await fs.rename(tempPath, targetPath);
  return targetPath;
}
